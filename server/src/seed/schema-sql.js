import { writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import db from '../db/index.js';
import '../models/index.js';

/**
 * Writes database/schema.sql — the full MySQL schema, runnable as-is in
 * MySQL Workbench (File → Open SQL Script → Execute). Regenerate after
 * changing a model:
 *
 *   npm run db:schema
 */
const out = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../../database/schema.sql');
const name = process.env.MYSQL_DATABASE || 'clinicsaathi';
const parts = [
  '-- ClinicSaathi MySQL schema (generated by `npm run db:schema` from server/src/models).',
  '-- Run in MySQL Workbench, or let the API create these tables itself on first start.',
  '',
  `CREATE DATABASE IF NOT EXISTS \`${name}\` CHARACTER SET utf8mb4 COLLATE utf8mb4_bin;`,
  `USE \`${name}\`;`,
  '',
];
for (const Model of db.models.values()) {
  parts.push(`-- ${Model.modelName}`);
  parts.push(db.tableDDL(Model), '');
}
mkdirSync(path.dirname(out), { recursive: true });
writeFileSync(out, parts.join('\n'));
console.log(`Wrote ${out} (${db.models.size} tables)`);
